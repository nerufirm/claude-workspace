4. `00_Context/brand-voice.md` のトーンに従い、箇条書きを用いた簡潔なサマリーレポートを作成する。

## Output
- フォーマット: Markdown (`.md`)
- 保存先: `reports/` フォルダ（存在しない場合は新規作成すること）
- ファイル名: `YYYY-MM-DD_WeeklyReport.md`

## Constraints
- 推測で成果を誇張しないこと。
- 実行前に必ず「実行計画」を提示し、私の承認を得ること。（完全自動化したい場合はこの行を削除し、「承認なしで即時保存すること」に変更してください）
